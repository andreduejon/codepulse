/** A help tab's rows: on Providers, each provider's section from its module, in the providers' order. */
export function helpRows(tab: HelpTab, modules: readonly { help?: readonly HelpRow[] }[]): readonly HelpRow[] {
  return tab === "providers" ? [...KEYBINDS.providers, ...modules.flatMap(module => module.help ?? [])] : KEYBINDS[tab];
}
