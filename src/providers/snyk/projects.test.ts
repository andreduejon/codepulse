import { afterEach, describe, expect, test } from "bun:test";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { discoverSnykDependencyProjects } from "./projects";

const roots: string[] = [];
const YARN_V1 = '# yarn lockfile v1\n\nexample@^1.0.0:\n  version "1.0.0"\n';
const YARN_MODERN = '# This file is generated by running "yarn install".\n\n__metadata:\n  version: 8\n';

afterEach(async () => {
  await Promise.all(roots.splice(0).map(path => rm(path, { recursive: true, force: true })));
});

async function fixture(files: Record<string, string> = {}): Promise<string> {
  const approvedTemp = join(tmpdir(), "opencode");
  const root = await mkdtemp(join(existsSync(approvedTemp) ? approvedTemp : tmpdir(), "codepulse-snyk-projects-test-"));
  roots.push(root);
  for (const [file, contents] of Object.entries(files)) {
    const path = join(root, file);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, contents);
  }
  return root;
}

describe("discoverSnykDependencyProjects", () => {
  test("discovers root and nested mixed projects without duplicating pnpm workspace manifests", async () => {
    const files = {
      "package.json": '{"packageManager":"pnpm@10.0.0"}',
      "pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
      "pnpm-workspace.yaml": "packages:\n  - packages/*\n",
      "packages/member/package.json": "{}",
      "apps/bun/package.json": '{"packageManager":"bun@1.3.0"}',
      "apps/bun/bun.lock": '{"lockfileVersion":1}',
      "apps/yarn/package.json": '{"packageManager":"yarn@1.22.22"}',
      "apps/yarn/yarn.lock": YARN_V1,
    };
    const root = await fixture(files);
    const tracked = Object.keys(files);

    expect(await discoverSnykDependencyProjects(root, tracked.reverse())).toEqual([
      { targetFile: "pnpm-lock.yaml", scanTargetFile: "pnpm-lock.yaml", packageManager: "pnpm" },
      { targetFile: "apps/bun/bun.lock", scanTargetFile: "apps/bun/yarn.lock", packageManager: "bun" },
      { targetFile: "apps/yarn/yarn.lock", scanTargetFile: "apps/yarn/yarn.lock", packageManager: "yarn" },
    ]);
    await expect(readFile(join(root, "apps/bun/yarn.lock"))).rejects.toMatchObject({ code: "ENOENT" });
    expect(await readFile(join(root, "apps/bun/bun.lock"), "utf8")).toBe(files["apps/bun/bun.lock"]);
  });

  test.each<[string | undefined, "bun" | "pnpm" | "yarn"]>([
    [undefined, "pnpm"],
    ["pnpm@10.0.0", "pnpm"],
    ["bun@1.3.0", "bun"],
    ["yarn@1.22.22", "yarn"],
  ])("selects %s packageManager with %s support", async (packageManager, expected) => {
    const files = {
      "package.json": JSON.stringify({ packageManager }),
      "bun.lock": "{}",
      "pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
      "yarn.lock": YARN_V1,
    };
    const root = await fixture(files);
    const projects = await discoverSnykDependencyProjects(root, Object.keys(files).reverse());

    expect(projects).toHaveLength(1);
    expect(projects[0]?.packageManager).toBe(expected);
  });

  test("prefers Bun over Yarn and falls back when the declared manager has no supported lock", async () => {
    const files = { "package.json": '{"packageManager":"pnpm@10.0.0"}', "bun.lock": "{}", "yarn.lock": YARN_V1 };
    const root = await fixture(files);
    expect(await discoverSnykDependencyProjects(root, Object.keys(files))).toEqual([
      { targetFile: "bun.lock", scanTargetFile: "yarn.lock", packageManager: "bun" },
    ]);
  });

  test("does not convert stale Bun lockfiles in a repository declaring npm", async () => {
    const files = {
      "package.json": '{"packageManager":"npm@11.0.0"}',
      "package-lock.json": "{}",
      "bun.lock": "{}",
      "pnpm-lock.yaml": "lockfileVersion: 9",
      "yarn.lock": YARN_V1,
    };
    const root = await fixture(files);
    expect(await discoverSnykDependencyProjects(root, Object.keys(files))).toEqual([]);
  });

  test.each(["package-lock.json", "npm-shrinkwrap.json"])(
    "preserves npm lockfile precedence over undeclared stale Bun input: %s",
    async lockfile => {
      const files = { "package.json": "{}", [lockfile]: "{}", "bun.lock": "{}" };
      const root = await fixture(files);
      expect(await discoverSnykDependencyProjects(root, Object.keys(files))).toEqual([]);
    },
  );

  test.each([
    ["{}", YARN_MODERN],
    ['{"packageManager":"yarn@4.9.0"}', YARN_V1],
    ["{}", `${YARN_V1}\n${YARN_MODERN}`],
    ["{}", '# comment mentioning # yarn lockfile v1\nexample:\n  version: "1.0.0"\n'],
  ])("does not discover modern or non-v1 Yarn: %s", async (manifest, lockfile) => {
    const root = await fixture({ "package.json": manifest, "yarn.lock": lockfile });
    expect(await discoverSnykDependencyProjects(root, ["package.json", "yarn.lock"])).toEqual([]);
  });

  test("accepts Yarn v1 with CRLF line endings", async () => {
    const root = await fixture({ "package.json": "{}", "yarn.lock": YARN_V1.replaceAll("\n", "\r\n") });
    expect(await discoverSnykDependencyProjects(root, ["package.json", "yarn.lock"])).toEqual([
      { targetFile: "yarn.lock", scanTargetFile: "yarn.lock", packageManager: "yarn" },
    ]);
  });

  test("only uses tracked same-directory manifests and locks, ignoring installed packages", async () => {
    const files = {
      "package.json": "{}",
      "bun.lock": "{}",
      "ignored/package.json": "{}",
      "ignored/yarn.lock": YARN_V1,
      "manifest-only/package.json": "{}",
      "manifest-only/bun.lock": "{}",
      "lock-only/package.json": "{}",
      "lock-only/pnpm-lock.yaml": "lockfileVersion: '9.0'\n",
      "orphan/bun.lock": "{}",
      "node_modules/installed/package.json": "{}",
      "node_modules/installed/bun.lock": "{}",
    };
    const root = await fixture(files);
    expect(
      await discoverSnykDependencyProjects(root, [
        "package.json",
        "bun.lock",
        "manifest-only/package.json",
        "lock-only/pnpm-lock.yaml",
        "orphan/bun.lock",
        "node_modules/installed/package.json",
        "node_modules/installed/bun.lock",
        "unrelated/missing.txt",
      ]),
    ).toEqual([{ targetFile: "bun.lock", scanTargetFile: "yarn.lock", packageManager: "bun" }]);
  });

  test("normalizes safe Windows-style paths and spaces without duplicate discovery", async () => {
    const root = await fixture({ "apps/my app/package.json": "{}", "apps/my app/bun.lock": "{}" });
    expect(
      await discoverSnykDependencyProjects(root, [
        ".\\apps\\my app\\package.json",
        "apps\\my app\\bun.lock",
        "apps//my app/./package.json",
        "apps/my app/bun.lock",
      ]),
    ).toEqual([{ targetFile: "apps/my app/bun.lock", scanTargetFile: "apps/my app/yarn.lock", packageManager: "bun" }]);
  });

  test.each([
    "/outside/package.json",
    "../package.json",
    "apps/../package.json",
    "apps\\..\\package.json",
    "C:\\outside\\package.json",
    "C:package.json",
    ".\\C:\\outside\\package.json",
    "\\\\server\\share\\package.json",
    "package.json\0",
    "",
  ])("rejects unsafe tracked paths: %s", async file => {
    const root = await fixture();
    await expect(discoverSnykDependencyProjects(root, [file])).rejects.toThrow(
      "safe repository-relative tracked paths",
    );
  });

  test.each(["package.json", "bun.lock", "pnpm-lock.yaml", "yarn.lock"])(
    "rejects tracked file symlinks: %s",
    async file => {
      const root = await fixture(file === "package.json" ? { "bun.lock": "{}" } : { "package.json": "{}" });
      const outside = await fixture({ "sensitive-file": file === "package.json" ? "{}" : YARN_V1 });
      await symlink(join(outside, "sensitive-file"), join(root, file), "file");

      const [project] = await discoverSnykDependencyProjects(root, [
        "package.json",
        file === "package.json" ? "bun.lock" : file,
      ]);
      expect(project.discoveryError).toContain("readable regular files without symlinks");
    },
  );

  test("rejects symlinked parent directories and worktree roots", async () => {
    const root = await fixture();
    const outside = await fixture({ "package.json": "{}", "bun.lock": "{}" });
    const linked = join(root, "linked");
    await symlink(outside, linked, process.platform === "win32" ? "junction" : "dir");

    const [project] = await discoverSnykDependencyProjects(root, ["linked/package.json", "linked/bun.lock"]);
    expect(project.discoveryError).toContain("readable regular files without symlinks");
    await expect(discoverSnykDependencyProjects(linked, ["package.json", "bun.lock"])).rejects.toThrow(
      "readable regular files without symlinks",
    );
  });

  test.each(["package.json", "bun.lock", "pnpm-lock.yaml", "yarn.lock"])(
    "reports missing tracked project files instead of empty support: %s",
    async missing => {
      const root = await fixture(missing === "package.json" ? { "bun.lock": "{}" } : { "package.json": "{}" });
      const [project] = await discoverSnykDependencyProjects(root, [
        "package.json",
        missing === "package.json" ? "bun.lock" : missing,
      ]);
      expect(project.discoveryError).toContain("readable regular files without symlinks");
      expect(project.discoveryError).not.toContain(root);
      expect(project.discoveryError).not.toContain("ENOENT");
    },
  );

  test("rejects directory lockfiles instead of reporting support", async () => {
    const root = await fixture({ "package.json": "{}" });
    await mkdir(join(root, "bun.lock"));
    const [project] = await discoverSnykDependencyProjects(root, ["package.json", "bun.lock"]);
    expect(project.discoveryError).toContain("readable regular files without symlinks");
  });

  test("keeps valid projects when a later tracked project cannot be read", async () => {
    const root = await fixture({ "package.json": "{}", "bun.lock": "{}", "nested/package.json": "{}" });
    const projects = await discoverSnykDependencyProjects(root, [
      "package.json",
      "bun.lock",
      "nested/package.json",
      "nested/yarn.lock",
    ]);
    expect(projects[0]).toEqual({ targetFile: "bun.lock", scanTargetFile: "yarn.lock", packageManager: "bun" });
    expect(projects[1]).toMatchObject({ targetFile: "nested/yarn.lock", packageManager: "yarn" });
    expect(projects[1].discoveryError).toContain("readable regular files without symlinks");
  });

  test.each(["invalid JSON with private content", "null", "[]", '"not an object"'])(
    "reports invalid manifests generically: %s",
    async manifest => {
      const root = await fixture({ "package.json": manifest, "bun.lock": "{}" });
      const [project] = await discoverSnykDependencyProjects(root, ["package.json", "bun.lock"]);
      expect(project.discoveryError).toContain("package.json contains valid JSON");
    },
  );

  test("returns no projects when the tracked list has no supported projects", async () => {
    const root = await fixture({ "package.json": "{}", "package-lock.json": "{}", "bun.lockb": "binary placeholder" });
    expect(await discoverSnykDependencyProjects(root, ["package.json", "package-lock.json", "bun.lockb"])).toEqual([]);
    expect(await discoverSnykDependencyProjects(root, [])).toEqual([]);
  });
});
